-- 3. Лайки (м-м): у каждого опубликованного признака от 3 до 4 лайков
INSERT INTO pancreatitis_sign_likes (user_id, sign_id)
SELECT u.id, s.id
FROM pancreatitis_users u
JOIN pancreatitis_signs s ON s.status = 'опубликован'
WHERE (u.id + s.id) % 3 <> 0;

